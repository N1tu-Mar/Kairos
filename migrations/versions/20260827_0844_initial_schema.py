def _existing_tables() -> set[str]:
    """What is already in the database, or nothing in offline mode.

    `--sql` has no connection to inspect — it renders the migration for a
    reviewer, and the thing worth reviewing is the full CREATE TABLE set. So
    offline mode reports an empty database and emits everything.
    """
    if context.is_offline_mode():
        return set()
    return set(sa.inspect(op.get_bind()).get_table_names())


