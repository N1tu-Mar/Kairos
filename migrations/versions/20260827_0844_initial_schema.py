def downgrade() -> None:
    """Drops every table. This deletes every run report, draft and profile.

    Present so the revision is complete and round-trippable in tests. It is
    not the rollback procedure — rolling back a deployment restores a backup
    (docs/runbooks.md). Reaching for this on a database that matters is how
    an audit trail stops existing.
    """
    for table in (
        "runs",
        "profiles",
        "opportunities",
        "jobs",
        "inbox",
        "drafts",
        "answers",
    ):
        op.drop_table(table)
